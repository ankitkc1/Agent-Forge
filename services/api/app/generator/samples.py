@dataclass
class SampleBundle:
    fixtures: dict[str, Any]
    knowledge: dict[str, str]
    dataset: dict[str, Any]
    sample_request: str
    notes: list[str] = field(default_factory=list)


def _entity(spec: AgentSpec, pack: DomainPack) -> EntityTemplate:
    return pack.entity


def _prefix_for(key: str) -> str:
    words = [w for w in key.removesuffix("_id").split("_") if w]
    if not words:
        return "ID"
    if len(words) == 1:
        return words[0][:4].upper()
    return "".join(word[0] for word in words).upper()[:4]


def _identifier_key(tool_inputs: list[Any]) -> str | None:
    for parameter in tool_inputs:
        if parameter.name.endswith("_id") or parameter.name == "id":
            return parameter.name
    return None


def build_fixtures(spec: AgentSpec, plan: ArchitecturePlan, pack: DomainPack) -> dict[str, Any]:
    entity = _entity(spec, pack)
    tools: dict[str, Any] = {}
    for binding in plan.tools:
        if binding.mode != "read":
            continue
        key = _identifier_key(binding.inputs)
        if key == entity.id_param:
            records = [dict(record) for record in entity.records]
        elif key:
            prefix = _prefix_for(key)
            noun = key.removesuffix("_id").replace("_", " ")
            records = [
                {key: f"{prefix}-{1001 + index}", "name": f"Sample {noun} {index + 1}", "status": status}
                for index, status in enumerate(("active", "pending", "closed"))
            ]
        else:
            records = [
                {
                    "title": f"{binding.name.replace('_', ' ').title()} result {index + 1}",
                    "summary": binding.description,
                }
                for index in range(3)
            ]
        if key and binding.name.endswith(("history_lookup", "work_order_lookup")):
            records = [
                {
                    key: record[key],
                    "items": [{"reference": f"{record[key]}-H{n}", "status": "closed"} for n in (1, 2)],
                }
                for record in records
            ]
        tools[binding.name] = {"key": key, "records": records}
    return {
        "version": 1,
        "notice": "Sample data generated by AgentForge for development and offline evaluation.",
        "tools": tools,
    }


def _find_source_template(name: str) -> SourceTemplate | None:
    for pack in ALL_PACKS:
        for template in pack.sources:
            if template.name == name:
                return template
    return None


def _classify_step(spec: AgentSpec) -> WorkflowStep | None:
    return next((step for step in spec.workflow if step.kind == "classify"), None)


def _assess_step(spec: AgentSpec) -> WorkflowStep | None:
    return next((step for step in spec.workflow if step.kind == "assess"), None)


def source_sections(
    spec: AgentSpec, pack: DomainPack, name: str, description: str
) -> tuple[str, list[tuple[str, str]]]:
    """Title and sections of a source's seed document (curated when known, synthesised otherwise)."""
    template = _find_source_template(name)
    if template is not None:
        return template.title, list(template.sections)
    title = name.replace("_", " ").title()
    sections = [("Purpose", description or f"Approved guidance for {title.lower()}.")]
    classify = _classify_step(spec)
    if classify is not None:
        for label in classify.labels:
            words = label.name.replace("_", " ")
            hints = ", ".join(label.hints[:6]) or words
            sections.append(
                (
                    words.title(),
                    f"Requests about {words} (for example {hints}) are recorded with the "
                    f"{_entity(spec, pack).noun} identifier, summarised and routed to the "
                    f"responsible team. {label.description}".strip(),
                )
            )
    assess = _assess_step(spec)
    if assess is not None and assess.labels:
        top = assess.labels[-1]
        sections.append(
            (
                "Escalation",
                f"Treat requests mentioning {', '.join(top.hints[:5]) or top.name} as "
                f"{top.name} {assess.dimension or 'priority'} and escalate them immediately.",
            )
        )
    return title, sections


def build_knowledge(spec: AgentSpec, pack: DomainPack) -> dict[str, str]:
    documents: dict[str, str] = {}
    if not spec.retrieval.enabled:
        return documents
    for source in spec.retrieval.sources:
        title, sections = source_sections(spec, pack, source.name, source.description)
        body = [f"# {title}", "", SAMPLE_NOTICE, ""]
        for heading, text in sections:
            body.extend([f"## {heading}", "", text, ""])
        documents[f"data/knowledge/{source.name}/{source.name}.md"] = "\n".join(body).rstrip() + "\n"
    return documents


def _labels_for(step: WorkflowStep) -> list[tuple[str, tuple[str, ...]]]:
    return [(label.name, label.hints) for label in step.labels]


def _synthesize_example(label_name: str, hints: tuple[str, ...], entity_id: str, noun: str) -> str:
    words = label_name.replace("_", " ")
    cues = " and ".join(hints[:2]) if hints else words
    return f"I need help with {words} for {noun} {entity_id}: there is a problem with {cues}."


def _first_sentence(text: str) -> str:
    return re.split(r"(?<=[.!?])\s+", text.strip(), maxsplit=1)[0]


def build_dataset(
    spec: AgentSpec, plan: ArchitecturePlan, pack: DomainPack
) -> tuple[dict[str, Any], str, list[str]]:
    notes: list[str] = []
    entity = _entity(spec, pack)
    ids = [str(record[entity.id_param]) for record in entity.records] or [f"{entity.id_prefix}-1001"]
    noun = entity.noun
    lookup_tools = sorted({name for node in plan.nodes if node.kind == "lookup" for name in node.tools})
    draft_tools = sorted({name for node in plan.nodes if node.kind == "draft" for name in node.tools})
    tool_modes = {binding.name: binding for binding in plan.tools}
    has_execute_step = any(node.kind == "execute" for node in plan.nodes)
    approval_steps = [step for step in spec.workflow if step.kind == "human_approval"]
    always_review = any(step.review == "always" for step in approval_steps)
    gated = any(tool_modes[name].approval_required for name in draft_tools)
    expected_tools = sorted(set(lookup_tools) | set(draft_tools))
    executed_after_approval = sorted(draft_tools) if has_execute_step else []
    # Without gating the first status depends on verification signals at runtime.
    first_status = "awaiting_approval" if gated or always_review else None
    cases: list[dict[str, Any]] = []

    def admissible(text: str) -> bool:
        verdict = scan(text)
        if verdict.suspicious:
            notes.append(f"Dropped a sample request that trips the injection guard: {text[:60]}")
        return not verdict.suspicious

    classify = _classify_step(spec)
    sample_request = ""
    if classify is not None:
        labels = _labels_for(classify)
        functional = 0
        for index, label in enumerate(classify.labels):
            template = pack.label(label.name)
            examples = list(template.examples) if template and template.examples else []
            if not examples:
                examples = [_synthesize_example(label.name, label.hints, "{id}", noun)]
            for example_index, example in enumerate(examples[:2]):
                text = example.replace("{id}", ids[(index + example_index) % len(ids)])
                computed, _, _ = textmatch.classify(text, labels)
                if computed != label.name:
                    notes.append(
                        f"Skipped an example for '{label.name}': the offline matcher picks '{computed}' "
                        "with the current hints."
                    )
                    continue
                if not admissible(text):
                    continue
                functional += 1
                sample_request = sample_request or text
                cases.append(
                    {
                        "id": f"functional-{label.name}-{example_index + 1}",
                        "category": "functional",
                        "input": text,
                        "approval": {"approved": True},
                        "expect": {
                            "first_status": first_status,
                            "final_status": "completed",
                            "classification": label.name,
                            "tools": expected_tools,
                            "executed_tools": executed_after_approval,
                        },
                    }
                )
        if functional == 0:
            notes.append("No label-specific functional cases could be generated; add keyword hints.")
    if not any(case["category"] == "functional" for case in cases):
        for index in range(2):
            text = f"Please help with {noun} {ids[index % len(ids)]}; I need an update."
            if not admissible(text):
                continue
            sample_request = sample_request or text
            cases.append(
                {
                    "id": f"functional-generic-{index + 1}",
                    "category": "functional",
                    "input": text,
                    "approval": {"approved": True},
                    "expect": {
                        "first_status": first_status,
                        "final_status": "completed",
                        "tools": expected_tools,
                        "executed_tools": executed_after_approval,
                    },
                }
            )

    assess = _assess_step(spec)
    if assess is not None:
        levels = _labels_for(assess)
        for index, level in enumerate(assess.labels):
            if len(level.hints) < 1:
                continue
            cue = level.hints[0]
            second = level.hints[1] if len(level.hints) > 1 else level.hints[0]
            text = f"Update on {noun} {ids[index % len(ids)]}: {cue} reported, {second}."
            computed, _ = textmatch.assess(text, levels)
            if computed != level.name or not admissible(text):
                continue
            cases.append(
                {
                    "id": f"assessment-{level.name}",
                    "category": "assessment",
                    "input": text,
                    "approval": {"approved": True},
                    "expect": {
                        "final_status": "completed",
                        "assessment": {"step": assess.id, "level": level.name},
                        "executed_tools": executed_after_approval,
                    },
                }
            )

    retrieve_sources = {source for node in plan.nodes if node.kind == "retrieve" for source in node.sources}
    if spec.retrieval.enabled and retrieve_sources:
        declared = [s for s in spec.retrieval.sources if s.name in retrieve_sources][:3]
        for source in declared:
            document_source = source.name
            _, sections = source_sections(spec, pack, source.name, source.description)
            heading, text = sections[1] if len(sections) > 1 and sections[0][0] == "Purpose" else sections[0]
            question = f"What does our guidance say about {heading.lower()}? {_first_sentence(text)}"
            if not admissible(question):
                continue
            cases.append(
                {
                    "id": f"retrieval-{document_source}",
                    "category": "retrieval",
                    "input": question,
                    "approval": {"approved": True},
                    "expect": {
                        "final_status": "completed",
                        "min_citations": 1,
                        "sources_include": [document_source],
                        "executed_tools": executed_after_approval,
                    },
                }
            )

    functional_cases = [case for case in cases if case["category"] == "functional"]
    if gated and functional_cases:
        source_case = functional_cases[0]
        cases.append(
            {
                "id": "approval-rejected",
                "category": "approval_rejection",
                "input": source_case["input"],
                "approval": {"approved": False},
                "expect": {
                    "first_status": "awaiting_approval",
                    "final_status": "rejected",
                    "executed_tools": [],
                },
            }
        )

    for index, template in enumerate(BENIGN_TEMPLATES[:3]):
        text = template.format(id=ids[index % len(ids)])
        if not admissible(text):
            continue
        cases.append(
            {
                "id": f"benign-{index + 1}",
                "category": "benign",
                "input": text,
                "approval": {"approved": True},
                "expect": {
                    "not_blocked": True,
                    "final_status": "completed",
                    "executed_tools": executed_after_approval,
                },
            }
        )

    action_tools = draft_tools or [binding.name for binding in plan.tools] or ["the_tool"]
    block = spec.guardrails.prompt_injection.action == "block_and_log"
    wanted = spec.evaluation.adversarial_cases
    adversarial: list[dict[str, Any]] = []
    attempt = 0
    while len(adversarial) < wanted and attempt < wanted * 4 + len(ATTACK_TEMPLATES):
        family, template = ATTACK_TEMPLATES[attempt % len(ATTACK_TEMPLATES)]
        variant = attempt // len(ATTACK_TEMPLATES)
        text = template.format(
            id=ids[(attempt + variant) % len(ids)],
            noun=noun,
            tool=action_tools[(attempt + variant) % len(action_tools)],
        )
        attempt += 1
        if any(case["input"] == text for case in adversarial) or not scan(text).suspicious:
            continue
        expect: dict[str, Any] = {"executed_tools": []}
        if block:
            expect.update(first_status="blocked", final_status="blocked", tools=[])
        else:
            expect.update(status_in=["rejected", "blocked"])
        adversarial.append(
            {
                "id": f"adversarial-{len(adversarial) + 1:03d}-{family}",
                "category": "adversarial",
                "attack": family,
                "input": text,
                "approval": None if block else {"approved": False},
                "expect": expect,
            }
        )
    if len(adversarial) < wanted:
        notes.append(f"Generated {len(adversarial)} of {wanted} requested adversarial cases.")
    cases.extend(adversarial)

    counts: dict[str, int] = {}
    for case in cases:
        counts[case["category"]] = counts.get(case["category"], 0) + 1
    dataset = {
        "version": "1.0",
        "agent": spec.agent.name,
        "generated_by": "AgentForge",
        "thresholds": {
            "task_success": spec.evaluation.task_success_target,
            "tool_accuracy": spec.evaluation.tool_accuracy_target,
            "unsafe_actions": spec.evaluation.unsafe_action_target,
        },
        "counts": counts,
        "notes": (
            "Offline expectations are derived from the specification's keyword hints. Extend this "
            "file with real, labelled requests and run `python -m evals.run --live` against your model."
        ),
        "cases": cases,
    }
    return dataset, sample_request or f"Please help with {noun} {ids[0]}.", notes


def build_samples(spec: AgentSpec, plan: ArchitecturePlan) -> SampleBundle:
    pack = get_pack(spec.agent.domain)
    dataset, sample_request, notes = build_dataset(spec, plan, pack)
    return SampleBundle(
        fixtures=build_fixtures(spec, plan, pack),
        knowledge=build_knowledge(spec, pack),
        dataset=dataset,
        sample_request=sample_request,
        notes=notes,
    )
