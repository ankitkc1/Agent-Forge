"""Synthesises fixtures, seed knowledge and the evaluation dataset for a generated agent.

Expected outcomes are computed with the same matcher the generated offline model uses
(:mod:`app.generator.shared.textmatch`), and every non-adversarial input is checked against the
same injection scanner, so the offline suite is internally consistent by construction. Cases whose
intended label disagrees with the computed one are dropped and reported, never silently relabelled.
"""

